function tauriConf(app, version) {
  return (
    JSON.stringify(
      {
        // No banner: Tauri validates this file against its schema and refuses
        // unknown keys, so the README beside it carries the provenance.
        $schema: 'https://schema.tauri.app/config/2',
        productName: app.title,
        // Overridden from the tag at release time (--config '{"version":...}'),
        // so a built bundle always reports the version it was released as.
        version,
        identifier: identifierFor(app),
        build: { frontendDist: '../src' },
        app: {
          withGlobalTauri: true,
          windows: [
            {
              label: 'main',
              title: app.title,
              width: 460,
              height: 500,
              resizable: false,
              maximizable: false,
              fullscreen: false,
              center: true,
            },
          ],
          security: { csp: null },
        },
        bundle: {
          active: true,
          targets: ['app', 'dmg', 'nsis', 'deb', 'rpm'],
          resources: ['launcher.toml', 'site/**/*'],
          icon: [
            'icons/32x32.png',
            'icons/128x128.png',
            'icons/128x128@2x.png',
            'icons/icon.icns',
            'icons/icon.ico',
          ],
          macOS: { minimumSystemVersion: '11.0' },
        },
      },
      null,
      2,
    ) + '\n'
  );
}

function infoPlist(app) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!--
${banner('  ', app.repo).trimEnd()}

  Merged into the bundle's Info.plist by tauri-bundler.

  Since macOS 15 an app must say why it talks to the local network, and without
  this key a double-clicked app is denied LAN traffic silently — no error, no
  prompt. It does not show up in development, because a process started from
  Terminal inherits Terminal's own permission. The string is shown verbatim in
  the permission prompt.
-->
<plist version="1.0">
<dict>
  <key>NSLocalNetworkUsageDescription</key>
  <string>${xml(app.title)} serves its page to browsers on your local network, so other machines in the room can open it.</string>
</dict>
</plist>
`;
}

const xml = (s) =>
  String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

