const DEFAULT_THEME = {
  bg: '#0f1115',
  panel: '#161a21',
  'panel-2': '#1d222b',
  border: '#2a2f3a',
  text: '#e8eaf0',
  muted: '#aab2c0',
  dim: '#6b7280',
  accent: '#7cc4ff',
  'accent-soft': '#17263a',
  good: '#37835c',
};

function launcherToml(app, hostPort) {
  const theme = { ...DEFAULT_THEME, ...(app.launcher?.theme ?? {}) };
  const notFound = app.notFound === 'spa' ? 'spa' : 'none';
  const themeLines = Object.entries(theme)
    .map(([k, v]) => `${/^[a-z]+$/.test(k) ? k : JSON.stringify(k)} = ${JSON.stringify(v)}`)
    .join('\n');
  return `${banner('#', app.repo)}#
# ${app.title} as a tray app: the launcher serves the built site itself.
#
# No child process and no [inject] block. The site is bundled as a resource
# and served in-process on the interface and port chosen in the panel — the
# same port the container and the Unraid template use, so the three agree.
# The site's _headers file ships beside it and is honoured, so this copy sends
# the same CSP and cache headers as the hosted one.

[app]
name = ${JSON.stringify(app.title)}
url = "http://{host}:{port}/"
default_port = ${hostPort}

[serve]
mode = "static"
dir = "{resource}/site"
not_found = ${JSON.stringify(notFound)}

[app.theme]
${themeLines}
`;
}

