// Translate a Cloudflare `_headers` file into nginx configuration.
//
// The `_headers` files in each repo are the source of truth for what the hosted
// site sends, and they are Cloudflare-specific — nginx has never heard of them.
// Copying the values across by hand guarantees drift the first time a CSP is
// tightened, so the container config is generated from the same file the edge
// uses.
//
// Two nginx behaviours drive the shape of the output:
//
//  1. `add_header` does NOT inherit into a `location` that declares any
//     `add_header` of its own. It is not additive and it is not a merge: the
//     child's list replaces the parent's list wholesale. A `/assets/*` block
//     that only sets Cache-Control would therefore silently drop every security
//     header for exactly the files that carry the application's JavaScript.
//     So the base `/*` headers are emitted into their own snippet and every
//     generated location `include`s it explicitly.
//
//  2. `add_header` only applies to a documented set of response codes unless
//     `always` is given. Without it the headers vanish on 404s and on the 304s
//     that a revalidating cache produces — which is most requests once a client
//     is warm. Everything is emitted with `always`.

/** Parse `_headers` into [{ pattern, headers: [[name, value], ...] }]. */
export function parseHeaders(text) {
  const groups = [];
  let current = null;

  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.replace(/\s+$/, '');
    if (!line.trim()) continue;
    // Comments are only comments at the start of a line. A `#` inside a header
    // value is a legitimate character (CSP hashes, URL fragments).
    if (line.trim().startsWith('#')) continue;

    if (!/^\s/.test(line)) {
      current = { pattern: line.trim(), headers: [] };
      groups.push(current);
      continue;
    }

    if (!current) continue;
    const idx = line.indexOf(':');
    if (idx === -1) continue;
    const name = line.slice(0, idx).trim();
    const value = line.slice(idx + 1).trim();
    if (name) current.headers.push([name, value]);
  }

  return groups;
}

/**
 * nginx string literal. Values arrive containing `;` (every CSP) and `'`
 * (CSP keywords like 'self'), both of which end or confuse a bare directive,
 * so everything is quoted. Backslash and double-quote are the only characters
 * that need escaping inside an nginx quoted string.
 */
function q(value) {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

function addHeaderLines(headers, indent = '    ') {
  return headers.map(([n, v]) => `${indent}add_header ${n} ${q(v)} always;`).join('\n');
}

/**
 * Map a `_headers` path pattern to an nginx location.
 *
 * `^~` matters: it stops nginx evaluating regex locations once this prefix
 * wins, which keeps a future regex block from stealing asset requests and
 * losing these headers with them.
 */
function patternToLocation(pattern) {
  if (pattern === '/*') return null; // the base group, handled separately
  const prefix = pattern.endsWith('/*') ? pattern.slice(0, -1) : pattern.replace(/\*$/, '');
  return `location ^~ ${prefix}`;
}

/**
 * Build the two generated files.
 *
 * @param {object} opts
 * @param {string|null} opts.headersText  contents of `_headers`, if the repo has one
 * @param {'spa'|'404page'|'none'} opts.notFound
 * @param {string} opts.repo  for the provenance comment
 * @param {string} opts.headersPath  for the provenance comment
 */
export function generateNginx({ headersText, notFound, repo, headersPath }) {
  const groups = headersText ? parseHeaders(headersText) : [];
  const base = groups.find((g) => g.pattern === '/*');
  const scoped = groups.filter((g) => g.pattern !== '/*');

  const provenance = headersText
    ? `# Generated from ${headersPath} in ${repo} by stoatworks-unraid/scripts/gen-docker.mjs.\n` +
      `# Edit that file and regenerate — changes made here are overwritten.`
    : `# Generated by stoatworks-unraid/scripts/gen-docker.mjs.\n` +
      `# ${repo} has no _headers file, so only the baseline headers below are applied.\n` +
      `# Edit the generator, not this file — changes made here are overwritten.`;

  // A repo with no _headers still gets a conservative baseline. These are the
  // three that are safe to assert for any of these apps without knowing what it
  // does: none of them are framed anywhere, none rely on MIME sniffing, and
  // none need to leak a full referrer. Deliberately no CSP — inventing one for
  // an app whose asset origins are unknown breaks it at runtime rather than at
  // build time, which is the worst place to find out.
  const baseHeaders = base
    ? base.headers
    : [
        ['X-Content-Type-Options', 'nosniff'],
        ['X-Frame-Options', 'DENY'],
        ['Referrer-Policy', 'strict-origin-when-cross-origin'],
      ];

  const headersSnippet = `${provenance}
#
# Included by every location block in nginx.conf. It has to be included rather
# than inherited: a location that sets any add_header of its own replaces the
# server-level list entirely instead of adding to it.

${addHeaderLines(baseHeaders, '')}
`;

  const rootBody =
    notFound === 'spa'
      ? `        # Mirrors not_found_handling = "single-page-application".\n` +
        `        try_files $uri $uri/ /index.html;`
      : notFound === '404page'
        ? `        try_files $uri $uri/ =404;`
        : `        try_files $uri $uri/ =404;`;

  const errorPage =
    notFound === '404page'
      ? `\n    # Mirrors not_found_handling = "404-page".\n    error_page 404 /404.html;\n    location = /404.html {\n        include /etc/nginx/snippets/stoatworks-headers.conf;\n        internal;\n    }\n`
      : '';

  const scopedBlocks = scoped
    .map((g) => {
      const loc = patternToLocation(g.pattern);
      if (!loc) return '';
      return `
    # from "${g.pattern}"
    ${loc} {
        include /etc/nginx/snippets/stoatworks-headers.conf;
${addHeaderLines(g.headers, '        ')}
        try_files $uri $uri/ =404;
    }
`;
    })
    .join('');

  const conf = `${provenance}

server {
    listen 80;
    server_name _;

    root /usr/share/nginx/html;
    index index.html;

    # There is deliberately no \`types { }\` block here. A \`types\` block does not
    # ADD to the inherited MIME map, it REPLACES it: declaring one at server
    # level throws away the whole of the http-level \`include mime.types\`, so
    # every .css and .js falls through to default_type
    # (application/octet-stream) and the site renders unstyled and scriptless.
    # \`nginx -t\` accepts it happily and the image builds green, so nothing
    # catches this before a browser does. nginx 1.27's own mime.types already
    # maps .wasm; the one gap, .mjs, is appended to that file in the Dockerfile
    # instead, which extends the map rather than replacing it.

    # Compress the text payloads. Not gzipping wasm/png/jpg on purpose: they are
    # already compressed and the CPU is wasted.
    gzip on;
    gzip_vary on;
    gzip_min_length 1024;
    gzip_types text/plain text/css text/javascript application/javascript application/json image/svg+xml;

    # Hide the nginx version from error pages and the Server header.
    server_tokens off;

    # The health endpoint the container HEALTHCHECK hits. Kept out of the access
    # log so a 30-second probe does not bury real traffic.
    location = /healthz {
        access_log off;
        add_header Content-Type "text/plain" always;
        return 200 "ok\\n";
    }
${scopedBlocks}
    location / {
        include /etc/nginx/snippets/stoatworks-headers.conf;
${rootBody}
    }
${errorPage}}
`;

  return { conf, headersSnippet };
}
