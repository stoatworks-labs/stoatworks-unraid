#!/usr/bin/env node
// Write a tray-app launcher into every browser tool's repo, from fleet.json.
//
// Usage:
//   node scripts/gen-launcher.mjs [--projects DIR] [--only repo,repo] [--dry-run] [--icons]
//
// Each static app in fleet.json gets a `launcher/` directory that builds as
// its own desktop app — a menu-bar tray app that serves the built site on a
// chosen interface and port, for the venue with no internet — plus a
// `.github/workflows/release-desktop.yml` that builds and attaches the
// installers when a `v*` tag is pushed.
//
// The shell is av-launcher, copied file for file from its checkout, the way
// srt-router, flock and RFutils each carry a copy. What differs per app is
// generated here: `launcher.toml` (a `[serve] mode = "static"` block, no child
// process), `tauri.conf.json`, `Info.plist`, the icons, `scripts/prepare.sh`
// and the workflow. Regenerating refreshes the shell in every launcher at
// once, which is the point of doing it from one place.
//
// Icons are the expensive part — `tauri icon` renders a dozen sizes — so they
// are only written when the icons directory is missing, or with --icons.
//
// Nothing here is sniffed from the target repo except the icon source; the
// served directory, the build command and the not-found policy all come from
// the same fleet.json entry the Dockerfile is generated from, so the container
// and the tray app cannot serve different things.

import {
  readFileSync,
  writeFileSync,
  mkdirSync,
  existsSync,
  readdirSync,
  statSync,
  copyFileSync,
  rmSync,
} from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { resolveRepo } from './repo-path.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');

const args = process.argv.slice(2);
const opt = (name, fallback) => {
  const i = args.indexOf(name);
  return i === -1 ? fallback : args[i + 1];
};
const PROJECTS = opt('--projects', null);
const ONLY = opt('--only', null)?.split(',').map((s) => s.trim());
const DRY = args.includes('--dry-run');
const ICONS = args.includes('--icons');

const fleet = JSON.parse(readFileSync(join(ROOT, 'fleet.json'), 'utf8'));
const unraid = JSON.parse(readFileSync(join(ROOT, 'unraid.json'), 'utf8'));

// The shell. Every launcher is a copy of this checkout's src/ and src-tauri/,
// and the commit it was copied from is recorded in each launcher's README so
// a stale copy can be told from a current one.
const SHELL = resolveRepo('av-launcher', PROJECTS);
if (!SHELL) {
  console.error('no av-launcher checkout found — the shell has to be copied from somewhere');
  process.exit(1);
}
const SHELL_SHA = execFileSync('git', ['-C', SHELL, 'rev-parse', '--short', 'HEAD'], {
  encoding: 'utf8',
}).trim();

// The files that ARE the shell. Anything else in av-launcher's tree is that
// repo's own business: its README, its openrcs build, its dev launcher.toml.
const SHELL_FILES = [
  'src/index.html',
  'src/styles.css',
  'src/main.js',
  'src-tauri/Cargo.toml',
  'src-tauri/Cargo.lock',
  'src-tauri/build.rs',
  'src-tauri/.gitignore',
  'src-tauri/capabilities/default.json',
  'src-tauri/src/config.rs',
  'src-tauri/src/lib.rs',
  'src-tauri/src/main.rs',
  'src-tauri/src/serve.rs',
  'scripts/release-lib.sh',
];
const SHELL_DIRS = ['src-tauri/crates/diag'];

// Fallback icon: the Stoatworks mark this repo serves to CA, 512 px square.
const FALLBACK_ICON = join(ROOT, 'icon.png');

const written = [];
const skipped = [];

function write(repoDir, relPath, contents, mode) {
  const full = join(repoDir, relPath);
  if (DRY) {
    written.push(`[dry] ${full}`);
    return;
  }
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, contents, mode ? { mode } : undefined);
  written.push(full);
}

function copy(src, repoDir, relPath) {
  const full = join(repoDir, relPath);
  if (DRY) {
    written.push(`[dry] ${full}  <- ${relative(SHELL, src)}`);
    return;
  }
  mkdirSync(dirname(full), { recursive: true });
  copyFileSync(src, full);
  written.push(full);
}

function copyDir(srcDir, repoDir, relDir) {
  for (const name of readdirSync(srcDir)) {
    const src = join(srcDir, name);
    if (statSync(src).isDirectory()) {
      if (name === 'target') continue;
      copyDir(src, repoDir, join(relDir, name));
    } else {
      copy(src, repoDir, join(relDir, name));
    }
  }
}

/** Shared header for every generated file, so nobody hand-edits one by mistake. */
function banner(comment, repo) {
  return `${comment} Generated by stoatworks-unraid/scripts/gen-launcher.mjs from fleet.json.
${comment} Repo: ${repo}. Edit fleet.json and regenerate — direct edits are overwritten.
`;
}

const identifierFor = (app) => app.launcher?.identifier ?? `com.allansargeant.${app.image}`;

/** The directory whose files the site is built from, and where an icon would be. */
function publicDir(app) {
  return app.kind === 'static-prebuilt' ? app.serveDir : 'public';
}

/** The first icon the repo ships, else the Stoatworks mark. */
function iconSource(app, repoDir) {
  if (app.launcher?.icon) return join(repoDir, app.launcher.icon);
  for (const candidate of ['icon-512.png', 'icon-1024.png', 'apple-touch-icon.png', 'icon.png']) {
    const p = join(repoDir, publicDir(app), candidate);
    if (existsSync(p)) return p;
  }
  return FALLBACK_ICON;
}

