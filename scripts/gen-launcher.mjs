function readme(app, hostPort) {
  const build =
    app.kind === 'static-build'
      ? `builds the site (\`${app.buildCmd}\` at the repo root)`
      : `takes the committed \`${app.serveDir}/\``;
  return `<!--
${banner('  ', app.repo).trimEnd()}
-->
# ${app.title} — desktop app

A small menu-bar app that serves ${app.title} on your own machine, for the
venue with no internet: pick a network interface and a port, press **Start**,
and open it from any browser in the room. It is the same page as
the hosted copy, served from inside the app — nothing is installed beside it
and nothing phones home.

Built with [Tauri v2](https://tauri.app) on the fleet's reusable
[av-launcher](https://github.com/stoatworks-labs/av-launcher) shell, using its
\`[serve] mode = "static"\`: the launcher serves the bundled \`site/\` directory
itself rather than supervising a server process. The site's \`_headers\` file
ships beside it and is honoured, so this copy sends the same security and
cache headers as the hosted one.

The default port is **${hostPort}**, the same one the container image and the
Unraid template use.

## Building from source

\`\`\`bash
cd launcher
npm install
bash scripts/prepare.sh      # ${build}, and stages it as src-tauri/site/
npm run tauri build          # -> src-tauri/target/release/bundle/
\`\`\`

\`npm run tauri dev\` works the same way after \`prepare.sh\`.

## What is generated

Everything in this directory comes from
[stoatworks-unraid](https://github.com/stoatworks-labs/stoatworks-unraid)'s
\`gen-launcher.mjs\`, reading the same \`fleet.json\` entry the Dockerfile is
generated from — so the served directory, the not-found policy and the port
cannot differ between the container and this app. The shell (\`src/\`,
\`src-tauri/src/\`, \`src-tauri/crates/\`) is a copy of av-launcher at
\`${SHELL_SHA}\`. Change either there and regenerate; edits made here are
overwritten.
`;
}

// ---------------------------------------------------------------------------
// scripts/prepare.sh
// ---------------------------------------------------------------------------

function prepareSh(app) {
  const stage =
    app.kind === 'static-build'
      ? `echo "==> building the site (${app.buildCmd})"
( cd "$REPO" && npm ci --no-audit --no-fund && ${app.buildCmd} )
SRC="$REPO/${app.outDir}"`
      : `# ${app.serveDir}/ is committed already built; there is nothing to run.
SRC="$REPO/${app.serveDir}"`;
  return `#!/usr/bin/env bash
${banner('#', app.repo)}#
# Stage the site the desktop app serves: build it from the repo (or take the
# committed copy), then copy it to src-tauri/site/, which tauri.conf.json
# bundles as a resource and launcher.toml serves as {resource}/site.
#
# Run before \`npm run tauri build\` or \`npm run tauri dev\`.
set -euo pipefail

HERE="$(cd "$(dirname "$0")/.." && pwd)"     # launcher/
REPO="$(cd "$HERE/.." && pwd)"               # the ${app.repo} repo root
SITE="$HERE/src-tauri/site"

${stage}

[ -f "$SRC/index.html" ] || { echo "error: $SRC has no index.html — nothing to serve" >&2; exit 1; }

echo "==> staging $SRC -> src-tauri/site"
rm -rf "$SITE"
mkdir -p "$SITE"
cp -R "$SRC/." "$SITE/"
# Cloudflare's redirect file has no meaning here; _headers stays, the launcher
# reads it and never serves it.
rm -f "$SITE/_redirects"
echo "staged $(find "$SITE" -type f | wc -l | tr -d ' ') files"
`;
}

// ---------------------------------------------------------------------------
// .github/workflows/release-desktop.yml
// ---------------------------------------------------------------------------

function workflow(app) {
  const ident = identifierFor(app);
  return `${banner('#', app.repo)}#
# Builds the ${app.title} desktop tray app (the av-launcher shell serving the
# built site) for macOS (one universal binary), Windows (x86_64) and Linux
# (x86_64), and attaches the installers to the release for the tag that
# triggered it.
#
# macOS ships ONE universal .dmg and .pkg rather than a pair of
# per-architecture ones, so an Intel Mac and an Apple Silicon Mac download the
# same file and nobody has to work out which they own. Tauri's
# \`universal-apple-darwin\` target builds both slices and lipos them; both were
# already being built on the Apple-Silicon runner before this (the Intel macOS
# runners are retired, so macos-13 is never used), so this merges them rather
# than adding a build.
#
# The x86_64 slice is therefore still never EXECUTED anywhere in CI, and it now
# hides inside the one file everybody downloads instead of in a separate one
# only Intel users took. The lipo gate below is the whole defence: simplecue
# once published an asset named macos-universal that was arm64 only, and
# configured, built, tested and uploaded clean while doing it.
#
# The macOS bundles leave here ad-hoc signed. The Developer ID key never
# leaves the author's Mac: a watcher there re-signs, notarises and re-uploads
# every new release's macOS assets within a few minutes (stoatworks-backend,
# release/auto-sign-watch.sh). Nothing in this workflow needs a secret.

name: release-desktop

on:
  workflow_dispatch:
    inputs:
      tag:
        description: 'Release tag to attach installers to (e.g. v0.1.0)'
        required: true
  push:
    tags: ['v*']

permissions:
  contents: write

jobs:
  build:
    name: \${{ matrix.name }}
    runs-on: \${{ matrix.os }}
    strategy:
      fail-fast: false
      matrix:
        include:
          # \`universal-apple-darwin\` is a Tauri *bundling* target, not a rustup
          # one — \`rustup target add universal-apple-darwin\` fails. So the
          # toolchain step installs \`rustTargets\`, which is the real triple (or
          # both real triples) behind each row, and \`target\` stays what is
          # handed to \`tauri build\` and names the output directory.
          - { name: macos-universal, os: macos-14,       target: universal-apple-darwin,   rustTargets: 'aarch64-apple-darwin,x86_64-apple-darwin' }
          - { name: windows-x86_64,  os: windows-latest, target: x86_64-pc-windows-msvc,   rustTargets: x86_64-pc-windows-msvc }
          - { name: linux-x86_64,    os: ubuntu-22.04,   target: x86_64-unknown-linux-gnu, rustTargets: x86_64-unknown-linux-gnu }
    steps:
      - uses: actions/checkout@v7

      - uses: actions/setup-node@v7
        with:
          node-version: 22

      - uses: dtolnay/rust-toolchain@stable
        with:
          targets: \${{ matrix.rustTargets }}

      - uses: Swatinem/rust-cache@v2
        with:
          key: launcher-\${{ matrix.target }}
          workspaces: 'launcher/src-tauri -> target'

      - name: Linux system dependencies
        if: startsWith(matrix.os, 'ubuntu')
        run: |
          sudo apt-get update
          sudo apt-get install -y libwebkit2gtk-4.1-dev libappindicator3-dev librsvg2-dev patchelf

      # The version the bundle reports is the tag's, not whatever the generated
      # tauri.conf.json carried when it was committed. Burrow reads it back out
      # of the built app's Info.plist and refuses an all-zero one.
      - name: Version from the tag
        id: ver
        shell: bash
        run: |
          tag="\${{ github.event.inputs.tag || github.ref_name }}"
          v="\${tag#v}"
          case "$v" in [0-9]*) ;; *) echo "not a version tag: $tag" >&2; exit 1 ;; esac
          echo "version=$v" >> "$GITHUB_OUTPUT"

      - name: Install launcher deps
        shell: bash
        run: cd launcher && npm install --no-audit --no-fund

      - name: Build and stage the site
        shell: bash
        run: bash launcher/scripts/prepare.sh

      - name: Build desktop bundle (macOS)
        if: startsWith(matrix.os, 'macos')
        shell: bash
        run: |
          cd launcher
          npm run tauri build -- --bundles app --target \${{ matrix.target }} \\
            --config "{\\"version\\":\\"\${{ steps.ver.outputs.version }}\\"}"

      - name: Build desktop bundle (Windows)
        if: startsWith(matrix.os, 'windows')
        shell: bash
        run: |
          cd launcher
          npm run tauri build -- --bundles nsis \\
            --config "{\\"version\\":\\"\${{ steps.ver.outputs.version }}\\"}"

      # AppImage bundling (linuxdeploy) is unreliable on CI runners; ship deb + rpm.
      - name: Build desktop bundle (Linux)
        if: startsWith(matrix.os, 'ubuntu')
        shell: bash
        run: |
          cd launcher
          npm run tauri build -- --bundles deb rpm \\
            --config "{\\"version\\":\\"\${{ steps.ver.outputs.version }}\\"}"

      # The only thing that proves a "universal" asset is universal. A Tauri
      # build that produced one slice looks identical in the log to one that
      # produced both, and the asset name is generated either way.
      #
      # Captured into a variable and matched with \`case\`, never piped into
      # grep: Actions runs \`shell: bash\` as \`bash -eo pipefail\`, so grep
      # exiting at its first match SIGPIPEs lipo and fails the step BECAUSE the
      # match was found. That trap has bitten this fleet repeatedly.
      - name: Verify the macOS bundle is universal
        if: startsWith(matrix.os, 'macos')
        shell: bash
        run: |
          appdir="launcher/src-tauri/target/\${{ matrix.target }}/release/bundle/macos"
          app=${JSON.stringify(`${app.title}.app`)}
          [ -d "$appdir/$app" ] || { echo "no .app produced" >&2; exit 1; }
          # The executable is whatever the bundle says it is, not the product
          # name with the spaces taken out or the crate name.
          exe="$(/usr/libexec/PlistBuddy -c 'Print :CFBundleExecutable' "$appdir/$app/Contents/Info.plist")"
          __archs="$( lipo -archs "$appdir/$app/Contents/MacOS/$exe" )"
          echo "$app/Contents/MacOS/$exe: $__archs"
          case "$__archs" in
            *arm64*) ;;
            *) echo "expected an arm64 slice, got: $__archs" >&2; exit 1 ;;
          esac
          case "$__archs" in
            *x86_64*) ;;
            *) echo "expected an x86_64 slice, got: $__archs" >&2; exit 1 ;;
          esac

      - name: Build the macOS .pkg and .dmg
        if: startsWith(matrix.os, 'macos')
        shell: bash
        # Tauri has no pkg bundler, and its dmg bundler's Finder step has failed
        # on a cross-compiled bundle, so both come from the fleet's release
        # helper and the same staged .app — which also keeps the artefact names
        # identical to the rest of the fleet's. Ad-hoc signed here; the
        # Developer ID signature and notarisation are applied post-hoc.
        run: |
          source launcher/scripts/release-lib.sh
          rl_init ${JSON.stringify(app.title)} ${app.image} "\${{ steps.ver.outputs.version }}" ${ident} "$GITHUB_WORKSPACE/out"
          appdir="launcher/src-tauri/target/\${{ matrix.target }}/release/bundle/macos"
          app=${JSON.stringify(`${app.title}.app`)}
          [ -d "$appdir/$app" ] || { echo "no .app produced" >&2; exit 1; }
          stage="$RUNNER_TEMP/stage-pkg"
          rm -rf "$stage"; mkdir -p "$stage" "$GITHUB_WORKSPACE/out"
          cp -R "$appdir/$app" "$stage/"
          rl_adhoc_sign "$stage/$app"
          rl_pkg "\${{ matrix.name }}" "$stage" --app "$app"
          rl_dmg "\${{ matrix.name }}" "$stage" --app "$app"

      - name: Collect installers
        shell: bash
        run: |
          mkdir -p out
          find launcher/src-tauri/target -type f \\
            \\( -name '*.msi' -o -name '*-setup.exe' -o -name '*.deb' -o -name '*.rpm' \\) \\
            -path '*/release/bundle/*' -exec cp {} out/ \\; || true
          ls -la out

      - uses: actions/upload-artifact@v7
        with:
          name: ${app.image}-desktop-\${{ matrix.name }}
          path: out/*
          if-no-files-found: error

      # A dispatch naming a tag that has not been pushed is a dry run: every
      # platform builds and the installers are kept as workflow artifacts, and
      # nothing is published. That is how a launcher is proven on all four
      # runners before the first real release is cut.
      - name: Attach installers to the release
        if: startsWith(github.ref, 'refs/tags/v') || github.event.inputs.tag != ''
        shell: bash
        env:
          GH_TOKEN: \${{ github.token }}
        run: |
          TAG="\${{ github.event.inputs.tag || github.ref_name }}"
          if ! git ls-remote --tags origin "refs/tags/$TAG" | grep -q .; then
            echo "tag $TAG is not pushed — dry run, installers are in the workflow artifacts"
            exit 0
          fi
          extra=""
          case "$TAG" in *-*) extra="--prerelease" ;; esac
          gh release view "$TAG" >/dev/null 2>&1 || \\
            gh release create "$TAG" --verify-tag --generate-notes --title "$TAG" $extra || true
          gh release upload "$TAG" out/* --clobber
`;
}

// ---------------------------------------------------------------------------

function icons(app, repoDir) {
  const dir = join(repoDir, 'launcher/src-tauri/icons');
  if (existsSync(join(dir, 'icon.icns')) && !ICONS) {
    skipped.push(`${app.repo}: icons already present (pass --icons to regenerate)`);
    return;
  }
  const src = iconSource(app, repoDir);
  if (DRY) {
    written.push(`[dry] ${dir}/*  <- tauri icon ${src}`);
    return;
  }
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  // The Tauri CLI lives in av-launcher's node_modules; every launcher declares
  // the same devDependency, so this is the same tool the repo would install.
  execFileSync('npx', ['--no-install', 'tauri', 'icon', src, '-o', dir], {
    cwd: SHELL,
    stdio: 'pipe',
  });
  // Mobile targets are not built; the android/ios trees are a hundred files
  // of noise in a repo that ships a menu-bar app.
  rmSync(join(dir, 'android'), { recursive: true, force: true });
  rmSync(join(dir, 'ios'), { recursive: true, force: true });
  written.push(`${dir}/*  <- ${relative(repoDir, src) || src}`);
}

function repoVersion(repoDir) {
  const pkg = join(repoDir, 'package.json');
  if (existsSync(pkg)) {
    const v = JSON.parse(readFileSync(pkg, 'utf8')).version;
    if (typeof v === 'string' && /^\d+\.\d+\.\d+/.test(v)) return v;
  }
  return '0.1.0';
}

for (const app of fleet.apps) {
  if (ONLY && !ONLY.includes(app.repo)) continue;
  if (!app.kind.startsWith('static')) continue;
  if (app.launcher?.skip) {
    skipped.push(`${app.repo}: launcher.skip set`);
    continue;
  }
  const repoDir = resolveRepo(app.checkoutDir || app.repo, PROJECTS);
  if (!repoDir) {
    skipped.push(`${app.repo}: no checkout found`);
    continue;
  }
  const hostPort = app.launcher?.defaultPort ?? unraid.apps[app.image]?.hostPort ?? 8080;
  const version = repoVersion(repoDir);

  for (const f of SHELL_FILES) copy(join(SHELL, f), repoDir, join('launcher', f));
  for (const d of SHELL_DIRS) copyDir(join(SHELL, d), repoDir, join('launcher', d));

  write(repoDir, 'launcher/README.md', readme(app, hostPort));
  write(repoDir, 'launcher/.gitignore', gitignore(app));
  write(repoDir, 'launcher/package.json', packageJson(app, version));
  write(repoDir, 'launcher/src-tauri/launcher.toml', launcherToml(app, hostPort));
  write(repoDir, 'launcher/src-tauri/tauri.conf.json', tauriConf(app, version));
  write(repoDir, 'launcher/src-tauri/Info.plist', infoPlist(app));
  write(repoDir, 'launcher/scripts/prepare.sh', prepareSh(app), 0o755);
  write(repoDir, '.github/workflows/release-desktop.yml', workflow(app));
  icons(app, repoDir);
}

console.log(`\nShell: av-launcher @ ${SHELL_SHA} (${SHELL})`);
console.log(`Wrote ${written.length} files.`);
for (const w of written) console.log('  ' + w);
if (skipped.length) {
  console.log(`\nNotes (${skipped.length}):`);
  for (const s of skipped) console.log('  ' + s);
}
